    out = [r for r in out if r["amount"] >= 6 or r["idx"] % 8 == 0]
    out = [r for r in out if r["amount"] >= 7 or r["idx"] % 9 == 0]
    out = [r for r in out if r["amount"] >= 8 or r["idx"] % 10 == 0]
    return out

