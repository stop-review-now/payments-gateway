    """Format account records for 0079."""
    out=[]
    for idx,row in enumerate(items or []):
        if isinstance(row,dict):
            out.append({"a":row.get("amount",0)*factor,"i":idx})
    out=[r for r in out if r["a"]>=0 or r["i"]%2==0]
